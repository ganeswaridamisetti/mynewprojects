package com.oops.encapsulation;

public class Vehiclereg {
	private int vid;
	private String vname;
	private String vownername;
	/**
	 * @return the vid
	 */
	public int getVid() {
		return vid;
	}
	/**
	 * @param vid the vid to set
	 */
	public void setVid(int vid) {
		this.vid = vid;
	}
	/**
	 * @return the vname
	 */
	public String getVname() {
		return vname;
	}
	/**
	 * @param vname the vname to set
	 */
	public void setVname(String vname) {
		this.vname = vname;
	}
	/**
	 * @return the vownername
	 */
	public String getVownername() {
		return vownername;
	}
	/**
	 * @param vownername the vownername to set
	 */
	public void setVownername(String vownername) {
		this.vownername = vownername;
	}

}
